export const extractApiError = (err, fallback) => {
  const data = err?.response?.data;
  const msg =
    data?.error?.message ||
    data?.detail ||
    (typeof data === "string" ? data : null) ||
    err?.message ||
    fallback;
  const details = Array.isArray(data?.error?.details) ? data.error.details : null;
  return { msg, details };
};

export const labelFromKey = (k) =>
  String(k || "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());

export const coerceNumber = (v, kind) => {
  if (v === "" || v === null || v === undefined) return v;
  const n = Number(v);
  if (Number.isNaN(n)) return v;
  return kind === "integer" ? Math.trunc(n) : n;
};

/**
 * Compare two flat param objects for equality.
 * Tolerates float/int differences (50000.0 === 50000) by converting to Number.
 */
export const paramsEqual = (a, b) => {
  const norm = (obj) => {
    const o = obj || {};
    return Object.keys(o)
      .sort()
      .map((k) => {
        const n = Number(o[k]);
        return `${k}=${Number.isFinite(n) ? n : o[k]}`;
      })
      .join(",");
  };
  return norm(a) === norm(b);
};
