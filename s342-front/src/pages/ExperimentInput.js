const extractApiError = (err, fallback) => {
  const data = err?.response?.data;
  const msg =
    data?.error?.message ||
    data?.detail ||
    (typeof data === "string" ? data : null) ||
    err?.message ||
    fallback;
  const details = Array.isArray(data?.error?.details)
    ? data.error.details
    : null;
  return { msg, details };
};

const labelFromKey = (k) =>
  String(k || "")
